const RCON = [
  0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
]

// ==================== 预计算 gmul 查找表 ====================
// 避免运行时逐位乘法，直接查表即可

function _gmul(a: number, b: number): number {
  let p = 0
  for (let i = 0; i < 8; i++) {
    if (b & 1) p ^= a
    const hi = a & 0x80
    a = (a << 1) & 0xff
    if (hi) a ^= 0x1b
    b >>= 1
  }
  return p
}

const MUL_9  = new Uint8Array(256)
const MUL_11 = new Uint8Array(256)
const MUL_13 = new Uint8Array(256)
const MUL_14 = new Uint8Array(256)

for (let i = 0; i < 256; i++) {
  MUL_9[i]  = _gmul(9, i)
  MUL_11[i] = _gmul(11, i)
  MUL_13[i] = _gmul(13, i)
  MUL_14[i] = _gmul(14, i)
}

// ==================== AES 基础运算 ====================

function invSubBytes(state: Uint8Array): void {
  for (let i = 0; i < 16; i++) state[i] = INV_SBOX[state[i]]
}

function invShiftRows(state: Uint8Array): void {
  let t: number
  t = state[13]; state[13] = state[9];  state[9]  = state[5]; state[5]  = state[1]; state[1] = t
  t = state[2];  state[2]  = state[10]; state[10] = t
  t = state[6];  state[6]  = state[14]; state[14] = t
  t = state[3];  state[3]  = state[7];  state[7]  = state[11]; state[11] = state[15]; state[15] = t
}

/** 逆列混合 — 使用预计算查找表 */
function invMixColumns(state: Uint8Array): void {
  for (let c = 0; c < 4; c++) {
    const i = c * 4
    const s0 = state[i], s1 = state[i+1], s2 = state[i+2], s3 = state[i+3]
    state[i]   = MUL_14[s0] ^ MUL_11[s1] ^ MUL_13[s2] ^ MUL_9[s3]
    state[i+1] = MUL_9[s0]  ^ MUL_14[s1] ^ MUL_11[s2] ^ MUL_13[s3]
    state[i+2] = MUL_13[s0] ^ MUL_9[s1]  ^ MUL_14[s2] ^ MUL_11[s3]
    state[i+3] = MUL_11[s0] ^ MUL_13[s1] ^ MUL_9[s2]  ^ MUL_14[s3]
  }
}

function addRoundKey(state: Uint8Array, roundKey: Uint8Array): void {
  for (let i = 0; i < 16; i++) state[i] ^= roundKey[i]
}

// ==================== AES 密钥扩展 ====================

/**
 * 将 16 字节密钥扩展为 176 字节（11 轮 × 16 字节）
 * 调用方可预计算一次，避免每个切片重复扩展
 */
export function keyExpansion(key: Uint8Array): Uint8Array {
  const w = new Uint8Array(176)
  w.set(key.subarray(0, 16))

  for (let i = 4; i < 44; i++) {
    const off = i * 4
    const prev = (i - 1) * 4
    const prev4 = (i - 4) * 4

    if (i % 4 === 0) {
      const t0 = SBOX[w[prev + 1]] ^ RCON[i / 4]
      const t1 = SBOX[w[prev + 2]]
      const t2 = SBOX[w[prev + 3]]
      const t3 = SBOX[w[prev]]
      w[off]     = w[prev4]     ^ t0
      w[off + 1] = w[prev4 + 1] ^ t1
      w[off + 2] = w[prev4 + 2] ^ t2
      w[off + 3] = w[prev4 + 3] ^ t3
    } else {
      w[off]     = w[prev]     ^ w[prev4]
      w[off + 1] = w[prev + 1] ^ w[prev4 + 1]
      w[off + 2] = w[prev + 2] ^ w[prev4 + 2]
      w[off + 3] = w[prev + 3] ^ w[prev4 + 3]
    }
  }

  return w
}

// ==================== AES-128 单块解密 ====================

function aesDecryptBlock(block: Uint8Array, expandedKey: Uint8Array): Uint8Array {
  const state = new Uint8Array(block)

  addRoundKey(state, expandedKey.subarray(160, 176))

  for (let round = 9; round >= 1; round--) {
    invShiftRows(state)
    invSubBytes(state)
    addRoundKey(state, expandedKey.subarray(round * 16, round * 16 + 16))
    invMixColumns(state)
  }

  invShiftRows(state)
  invSubBytes(state)
  addRoundKey(state, expandedKey.subarray(0, 16))

  return state
}

// ==================== PKCS7 去填充 ====================

function removePKCS7Padding(data: Uint8Array): Uint8Array {
  if (data.length === 0) return data
  const padLen = data[data.length - 1]
  if (padLen === 0 || padLen > 16) return data
  for (let i = data.length - padLen; i < data.length; i++) {
    if (data[i] !== padLen) return data
  }
  return data.subarray(0, data.length - padLen)
}

// ==================== 公开 API ====================

/**
 * AES-128-CBC 解密（使用预计算的扩展密钥）
 * 适用于批量解密场景：先调用 keyExpansion 一次，再对每个切片调用此函数
 */
export function aes128CBCDecryptWithExpandedKey(
  encrypted: Uint8Array,
  expandedKey: Uint8Array,
  iv: Uint8Array,
): Uint8Array {
  const blockSize = 16
  const numBlocks = Math.ceil(encrypted.length / blockSize)
  const decrypted = new Uint8Array(encrypted.length)

  let prev = iv

  for (let i = 0; i < numBlocks; i++) {
    const start = i * blockSize
    const end = Math.min(start + blockSize, encrypted.length)
    const block = new Uint8Array(blockSize)
    block.set(encrypted.subarray(start, end))

    const plain = aesDecryptBlock(block, expandedKey)

    for (let j = 0; j < blockSize; j++) {
      decrypted[start + j] = plain[j] ^ prev[j]
    }

    prev = encrypted.subarray(start, end)
  }

  return removePKCS7Padding(decrypted)
}

/**
 * AES-128-CBC 解密（便捷版本，内部自动扩展密钥）
 */
export function aes128CBCDecrypt(
  encrypted: Uint8Array,
  key: Uint8Array,
  iv: Uint8Array,
): Uint8Array {
  const expandedKey = keyExpansion(key)
  return aes128CBCDecryptWithExpandedKey(encrypted, expandedKey, iv)
}

/**
 * AES-128-CBC 异步解密（分块处理，每块之间让出主线程）
 * 防止大文件解密时 UI 卡死或闪退
 */
export async function aes128CBCDecryptAsync(
  encrypted: Uint8Array,
  expandedKey: Uint8Array,
  iv: Uint8Array,
  onProgress?: (processedBlocks: number, totalBlocks: number) => void,
): Promise<Uint8Array> {
  const blockSize = 16
  const numBlocks = Math.ceil(encrypted.length / blockSize)
  const decrypted = new Uint8Array(encrypted.length)

  let prev = iv
  // 每次处理 4096 个块（64KB），减少大量分片解密时的调度开销。
  // 加密 m3u8 依赖这些让出机会刷新页面和实时活动，块太大会显得进度滞后。
  const CHUNK = 4096

  for (let i = 0; i < numBlocks; i += CHUNK) {
    const end = Math.min(i + CHUNK, numBlocks)

    for (let j = i; j < end; j++) {
      const s = j * blockSize
      const e = Math.min(s + blockSize, encrypted.length)
      const block = new Uint8Array(blockSize)
      block.set(encrypted.subarray(s, e))

      const plain = aesDecryptBlock(block, expandedKey)
      for (let k = 0; k < blockSize; k++) {
        decrypted[s + k] = plain[k] ^ prev[k]
      }
      prev = encrypted.subarray(s, e)
    }

    onProgress?.(end, numBlocks)

    // 让出主线程，允许 UI 更新和事件处理
    await new Promise<void>(r => setTimeout(() => r(), 0))
  }

  return removePKCS7Padding(decrypted)
}

/**
 * 将 M3U8 中的 IV 字符串解析为 16 字节 Uint8Array
 * 支持格式: "0x00000000000000000000000000000001"
 * 如果 ivHex 为 null，则用 seq 作为 128-bit 大端整数
 */
export function parseM3u8IV(ivHex: string | null, seq: number): Uint8Array {
  if (ivHex) {
    const hex = ivHex.replace(/^0x/i, "").padStart(32, "0")
    const bytes = new Uint8Array(16)
    for (let i = 0; i < 16; i++) {
      bytes[i] = parseInt(hex.substring(i * 2, i * 2 + 2), 16)
    }
    return bytes
  }
  const iv = new Uint8Array(16)
  iv[12] = (seq >>> 24) & 0xff
  iv[13] = (seq >>> 16) & 0xff
  iv[14] = (seq >>> 8)  & 0xff
  iv[15] =  seq         & 0xff
  return iv
}
